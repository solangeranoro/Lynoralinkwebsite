function legalBody(copy, items) {
  const toc = items.map(([title], i) => `<a href="#s${i}">${title}</a>`).join("");
  const body = items.map(([title, text], i) => `<section id="s${i}"><h2>${title}</h2><p>${text}</p></section>`).join("");
  return `<div class="legal"><nav class="toc" aria-label="${copy.tocLabel}"><p>${copy.tocLabel}</p>${toc}</nav><div class="legal-body">${body}</div></div>`;
}

function enhancePage() {
  const input = root.querySelector("#faq-q");
  if (input) {
    const items = [...root.querySelectorAll(".faq-list details")], empty = root.querySelector(".faq-empty");
    input.addEventListener("input", () => {
      const q = input.value.trim().toLowerCase();
      let n = 0;
      items.forEach((d) => { const hit = !q || d.textContent.toLowerCase().includes(q); d.hidden = !hit; if (hit) n++; });
      empty.hidden = n > 0;
    });
  }
  const links = [...root.querySelectorAll(".toc a")];
  if (links.length && "IntersectionObserver" in window) {
    const io = new IntersectionObserver((entries) => entries.forEach((e) => {
      if (e.isIntersecting) links.forEach((a) => a.classList.toggle("on", a.getAttribute("href") === `#${e.target.id}`));
    }), { rootMargin: "-25% 0px -65% 0px" });
    root.querySelectorAll(".legal-body section").forEach((sec) => io.observe(sec));
  }
}

window.addEventListener("scroll", () => {
  document.querySelector(".page-header")?.classList.toggle("on", window.scrollY > 30);
}, { passive: true });

