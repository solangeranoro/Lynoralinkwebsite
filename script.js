const carouselSlides = [
  { image: 0, label: "slide0Label", title: "slide0Title", copy: "slide0Copy" },
  { image: 1, label: "slide1Label", title: "slide1Title", copy: "slide1Copy" },
  { image: 2, label: "slide2Label", title: "slide2Title", copy: "slide2Copy" },
];

const carousel = document.querySelector(".carousel");
const localeButtons = document.querySelectorAll("[data-locale]");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
let locale = "fr";
let activeSlide = 0;
let isHovered = false;
let isFocused = false;
let isInView = true;
let rotationTimer;

function updateMenuLabel() {
  const menuButton = document.querySelector(".menu-toggle");
  if (!menuButton) return;
  const dictionary = translations[locale];
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-label", dictionary[isOpen ? "closeMenu" : "openMenu"]);
}

function pointAppLinksToCurrentEnvironment() {
  const appOrigin = "https://app.lynoralink.com";

  document.querySelectorAll("[data-app-route]").forEach((link) => {
    link.href = new URL(link.dataset.appRoute, appOrigin).href;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });
}

function translatePage() {
  const dictionary = translations[locale];
  document.documentElement.lang = locale;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]').content = dictionary.metaDescription;
  document.querySelector('meta[property="og:title"]').content = dictionary.pageTitle;
  document.querySelector('meta[property="og:description"]').content = dictionary.ogDescription;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation) element.textContent = translation;
  });

  localeButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.locale === locale));
  });
  updateMenuLabel();
  document.querySelector(".nav-links").setAttribute("aria-label", locale === "fr" ? "Navigation principale" : "Main navigation");
  if (carousel) {
    carousel.setAttribute("aria-label", dictionary.carouselLabel);
    carousel.setAttribute("aria-roledescription", locale === "fr" ? "carrousel" : "carousel");
    carousel.querySelector(".carousel-dots").setAttribute("aria-label", dictionary.chooseSlide);
  }
  renderSlide();
}

function renderSlide() {
  if (!carousel) return;
  const dictionary = translations[locale];
  const slide = carouselSlides[activeSlide];
  carousel.querySelectorAll(".carousel-image").forEach((image, index) => {
    const isActive = index === activeSlide;
    image.classList.toggle("is-active", isActive);
    image.setAttribute("aria-hidden", String(!isActive));
    image.setAttribute("aria-label", `${index + 1} / 3: ${dictionary[carouselSlides[index].title]}`);
    image.setAttribute("aria-roledescription", locale === "fr" ? "diapositive" : "slide");
  });
  carousel.querySelector(".slide-count").textContent = `${String(activeSlide + 1).padStart(2, "0")} / 03`;
  carousel.querySelector(".carousel-label [data-i18n]").textContent = dictionary[slide.label];
  carousel.querySelector(".carousel-caption h3").textContent = dictionary[slide.title];
  carousel.querySelector(".carousel-caption > div > p:last-child").textContent = dictionary[slide.copy];
  carousel.querySelectorAll(".carousel-dots button").forEach((button, index) => {
    button.setAttribute("aria-pressed", String(index === activeSlide));
    button.setAttribute("aria-label", `${dictionary.showSlide} ${index + 1}: ${dictionary[carouselSlides[index].label]}`);
  });
}

function showSlide(index) {
  activeSlide = (index + carouselSlides.length) % carouselSlides.length;
  renderSlide();
}

function updateRotation() {
  window.clearInterval(rotationTimer);
  if (reducedMotion || isHovered || isFocused || !isInView) return;
  rotationTimer = window.setInterval(() => showSlide(activeSlide + 1), 6000);
}

const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector("#primary-menu");

function closeNavigation() {
  if (!menuButton || !navigation) return;
  menuButton.setAttribute("aria-expanded", "false");
  navigation.classList.remove("is-open");
  updateMenuLabel();
}

menuButton?.addEventListener("click", () => {
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isOpen));
  navigation.classList.toggle("is-open", !isOpen);
  updateMenuLabel();
});

navigation?.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeNavigation));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeNavigation();
});

localeButtons.forEach((button) => {
  button.addEventListener("click", () => {
    locale = button.dataset.locale;
    try {
      window.localStorage.setItem("lynora.locale", locale);
    } catch (error) {
      console.warn("Could not save the language preference.", error);
    }
    translatePage();
  });
});

carousel?.querySelectorAll(".carousel-dots button").forEach((button, index) => {
  button.addEventListener("click", () => showSlide(index));
});
carousel?.addEventListener("mouseenter", () => { isHovered = true; updateRotation(); });
carousel?.addEventListener("mouseleave", () => { isHovered = false; updateRotation(); });
carousel?.addEventListener("focusin", () => { isFocused = true; updateRotation(); });
carousel?.addEventListener("focusout", (event) => {
  if (!carousel.contains(event.relatedTarget)) {
    isFocused = false;
    updateRotation();
  }
});

if (carousel && "IntersectionObserver" in window) {
  const observer = new IntersectionObserver(([entry]) => {
    isInView = entry.isIntersecting;
    updateRotation();
  }, { rootMargin: "120px" });
  observer.observe(carousel);
}

if ("IntersectionObserver" in window && !reducedMotion) {
  const animatedItems = document.querySelectorAll(".step, .feature, .audience-grid article, .community-copy, .community-points, .carousel");
  if (animatedItems.length) {
    document.body.classList.add("motion-ready");
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    }, { threshold: 0.12, rootMargin: "0px 0px -36px 0px" });
    animatedItems.forEach((item) => revealObserver.observe(item));
  }
}

const year = document.querySelector("#current-year");
if (year) year.textContent = String(new Date().getFullYear());

try {
  const storedLocale = window.localStorage.getItem("lynora.locale");
  if (storedLocale === "en" || storedLocale === "fr") locale = storedLocale;
} catch (error) {
  console.warn("Could not read the saved language preference.", error);
}

translatePage();
pointAppLinksToCurrentEnvironment();
updateRotation();

const splash = document.querySelector("#lynora-splash");
if (splash) {
  document.body.classList.add("splash-active");
  const splashDuration = matchMedia("(prefers-reduced-motion: reduce)").matches ? 3500 : 5500;
  window.setTimeout(() => {
    splash.classList.add("is-leaving");
    window.setTimeout(() => {
      splash.remove();
      document.body.classList.remove("splash-active");
    }, 220);
  }, splashDuration);
}
